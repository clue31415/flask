def predict_symptoms(user_input: str, top_k: int = 10):
    text = normalize(user_input)

    scores = defaultdict(int)
    evidence = {}

    # 1️⃣ 계통 순회
    for system, data in symptom_db.items():

        index_keywords = data["index"]
        items = data["items"]

        # 2️⃣ 계통 매칭 (index 기반)
        system_match = any(
            normalize(k) in text for k in index_keywords
        )

        # 계통이 전혀 안 맞으면 스킵
        if not system_match:
            continue

        # 3️⃣ 실제 증상 매칭
        for group in items:
            for keyword in group:
                nk = normalize(keyword)

                if nk and nk in text:
                    key = (system, group[0])
                    scores[key] += 1
                    evidence[key] = keyword

    # 4️⃣ 정렬
    sorted_results = sorted(
        scores.items(),
        key=lambda x: x[1],
        reverse=True
    )

    # 5️⃣ 결과 출력
    output = []
    for (system, symptom), score in sorted_results[:top_k]:
        output.append({
            "계통": system,
            "의심증상": symptom,
            "근거": evidence[(system, symptom)],
            "점수": score
        })

    return output


